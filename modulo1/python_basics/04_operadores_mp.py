# Operadores Matemáticos - Control de Carga Portuaria
toneladas_cargadas = 15
toneladas_descargadas = 20
print ("Suma de carga total")
print (toneladas_cargadas,"+",toneladas_descargadas, "=", toneladas_cargadas+toneladas_descargadas)
print ("Diferencia de toneladas")
print (toneladas_cargadas,"-",toneladas_descargadas, "=", toneladas_cargadas-toneladas_descargadas)
print ("Multiplicación de tarifas portuarias")
print (toneladas_cargadas,"*",toneladas_descargadas, "=", toneladas_cargadas*toneladas_descargadas)
print ("Potencia de capacidad")
print (toneladas_cargadas,"**",toneladas_descargadas, "=", toneladas_cargadas**toneladas_descargadas)
print ("Division de carga por muelle")
print (toneladas_cargadas,"/",toneladas_descargadas, "=", toneladas_cargadas/toneladas_descargadas)
print ("Division Entera de contenedores por bahía")
print (toneladas_cargadas,"//",toneladas_descargadas, "=", toneladas_cargadas//toneladas_descargadas)
print ("Módulo de distribución de carga")
print (toneladas_cargadas,"%",toneladas_descargadas, "=", toneladas_cargadas%toneladas_descargadas)
print ("Operadores de Asignación")
